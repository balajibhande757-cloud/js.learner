// prefix
let p = 5;

let q = ++p;

console.log(p); // 6
console.log(q); // 6

//postfix
let x = 5;

let y = x++;

console.log(x); // 6
console.log(y); // 6


/*

| Type              | Syntax | Action                   |
| ----------------- | ------ | ------------------------ |
| Prefix Increment  | `++x`  | Increase first, then use |
| Postfix Increment | `x++`  | Use first, then increase |
| Prefix Decrement  | `--x`  | Decrease first, then use |
| Postfix Decrement | `x--`  | Use first, then decrease |

*/